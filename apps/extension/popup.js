const pageStatus = document.getElementById("pageStatus");
const observerStatus = document.getElementById("observerStatus");
const syncStatus = document.getElementById("syncStatus");
const lastSubmission = document.getElementById("lastSubmission");
const apiBaseInput = document.getElementById("apiBase");
const tokenInput = document.getElementById("token");
const connectButton = document.getElementById("connect");
const disconnectButton = document.getElementById("disconnect");
const retryButton = document.getElementById("retry");

function renderState(data) {
  if (data.lastPageContext) {
    pageStatus.textContent = "Detected " + data.lastPageContext.platform + ": " + data.lastPageContext.title;
  } else {
    pageStatus.textContent = "Open a LeetCode problem to detect the current page.";
  }

  observerStatus.textContent = data.lastObserverStatus || "Observer has not reported a status yet.";
  syncStatus.textContent = data.lastSyncStatus || (data.extensionToken ? "Extension key saved." : "Not connected.");

  if (data.lastAcceptedSubmission) {
    const item = data.lastAcceptedSubmission;
    lastSubmission.textContent = "Last accepted: " + item.title + (item.language ? " · " + item.language : "");
  } else {
    lastSubmission.textContent = "No accepted submission captured yet.";
  }

  if (data.apiBase) apiBaseInput.value = data.apiBase;
  tokenInput.placeholder = data.extensionToken ? "Key saved (enter a new key to replace)" : "Paste key from your dashboard";
}

const stateKeys = ["lastPageContext", "lastObserverStatus", "lastSyncStatus", "lastAcceptedSubmission", "extensionToken", "apiBase"];
chrome.storage.local.get(stateKeys, renderState);
chrome.storage.onChanged.addListener((_changes, areaName) => {
  if (areaName !== "local") return;
  chrome.storage.local.get(stateKeys, renderState);
});

function parseApiBase(rawValue) {
  let url;
  try {
    url = new URL(rawValue.trim());
  } catch {
    throw new Error("Enter a valid DSAHub URL, for example https://your-domain.vercel.app.");
  }

  if (url.username || url.password || url.search || url.hash || (url.pathname !== "/" && url.pathname !== "")) {
    throw new Error("Enter only the DSAHub origin, without a path, credentials, query or fragment.");
  }

  const localHost = url.hostname === "localhost" || url.hostname === "127.0.0.1";
  if (url.protocol !== "https:" && !(url.protocol === "http:" && localHost)) {
    throw new Error("Hosted DSAHub URLs must use HTTPS. HTTP is allowed only for localhost development.");
  }

  if (localHost && url.port !== "3000") {
    throw new Error("Local development must use http://localhost:3000 or http://127.0.0.1:3000.");
  }

  return url.origin;
}

async function ensureApiHostPermission(apiBase) {
  const url = new URL(apiBase);
  if (url.hostname === "localhost" || url.hostname === "127.0.0.1") return true;

  const originPattern = url.origin + "/*";
  const granted = await chrome.permissions.request({ origins: [originPattern] });
  if (!granted) {
    throw new Error("Chrome permission was not granted for " + url.host + ". The extension cannot contact this DSAHub server.");
  }
  return true;
}

connectButton.addEventListener("click", async () => {
  const token = tokenInput.value.trim();
  let apiBase;

  if (!token || !/^[A-Za-z0-9_-]{40,64}$/.test(token)) {
    syncStatus.textContent = "Paste a valid extension key generated by your DSAHub dashboard.";
    return;
  }

  try {
    apiBase = parseApiBase(apiBaseInput.value);
    connectButton.disabled = true;
    syncStatus.textContent = "Requesting access to the selected DSAHub server…";
    await ensureApiHostPermission(apiBase);

    await chrome.storage.local.set({ extensionToken: token, apiBase });
    tokenInput.value = "";
    syncStatus.textContent = "Connection saved. Checking the last accepted submission…";

    chrome.runtime.sendMessage({ type: "DSAHUB_RETRY_LAST_SUBMISSION" }, (result) => {
      if (chrome.runtime.lastError) {
        syncStatus.textContent = "Connection saved. Reload the extension and retry sync.";
        return;
      }
      if (result?.error) syncStatus.textContent = result.error;
      chrome.storage.local.get(["lastSyncStatus"], (data) => {
        if (data.lastSyncStatus) syncStatus.textContent = data.lastSyncStatus;
      });
    });
  } catch (error) {
    syncStatus.textContent = error instanceof Error ? error.message : "Could not save the DSAHub connection.";
  } finally {
    connectButton.disabled = false;
  }
});

disconnectButton.addEventListener("click", async () => {
  await chrome.storage.local.remove(["extensionToken"]);
  syncStatus.textContent = "Disconnected on this browser. Revoke the key from the dashboard to invalidate it everywhere.";
  tokenInput.value = "";
});

retryButton.addEventListener("click", () => {
  syncStatus.textContent = "Retrying last submission…";
  chrome.runtime.sendMessage({ type: "DSAHUB_RETRY_LAST_SUBMISSION" }, (result) => {
    if (chrome.runtime.lastError) {
      syncStatus.textContent = "Could not contact the extension background service.";
      return;
    }
    if (result?.error) syncStatus.textContent = result.error;
    chrome.storage.local.get(["lastSyncStatus"], (data) => {
      syncStatus.textContent = data.lastSyncStatus || syncStatus.textContent;
    });
  });
});
